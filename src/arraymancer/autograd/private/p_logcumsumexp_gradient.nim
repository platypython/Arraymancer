proc gradientMultiplyAdd(a, b, c: float32): float32
  {.importc: "fmaf", header: "<math.h>".}

proc gradientExponential(value: float32): float32 {.inline.} =
  ## Matching the rounded channels matters when their subtraction cancels.
  if value != value: return value
  if value < -104'f32: return 0'f32
  if value > 100'f32: return Inf.float32
  let scaled = value * 1.4426950408889634073599246810018921374'f32
  let lower = floor(scaled)
  let fraction = scaled - lower
  var exponent = int(lower)
  if fraction > 0.5'f32 or (fraction == 0.5'f32 and (exponent and 1) != 0):
    inc exponent
  var remainder = gradientMultiplyAdd(float32(exponent), -0.693145751953125'f32, value)
  remainder = gradientMultiplyAdd(float32(exponent), -1.428606765330187045e-6'f32, remainder)
  var polynomial = 0.000198527617612853646278381'f32
  polynomial = gradientMultiplyAdd(polynomial, remainder, 0.00139304355252534151077271'f32)
  polynomial = gradientMultiplyAdd(polynomial, remainder, 0.00833336077630519866943359'f32)
  polynomial = gradientMultiplyAdd(polynomial, remainder, 0.0416664853692054748535156'f32)
  polynomial = gradientMultiplyAdd(polynomial, remainder, 0.166666671633720397949219'f32)
  polynomial = gradientMultiplyAdd(polynomial, remainder, 0.5'f32)
  let reduced = 1'f32 + gradientMultiplyAdd(remainder * remainder, polynomial, remainder)
  # Both scale factors are normal; only the final multiply can round a subnormal.
  let first = exponent div 2
  let scaleFirst = cast[float32](uint32(first + 127) shl 23)
  let scaleSecond = cast[float32](uint32(exponent - first + 127) shl 23)
  (reduced * scaleFirst) * scaleSecond

proc gradientExponential(value: float64): float64 {.inline.} =
  exp(value)

proc realGradientStep[F: SomeFloat](positive, negative: var float64;
    input, normalizer, seed: F): F {.inline.} =
  ## The finite sentinel and both rounded prefixes are part of the VJP contract.
  let minimum = when F is float32: F(-3.4028234663852886e38)
                else: F(-1.7976931348623157e308)
  var positiveLog, negativeLog = minimum
  if seed > F(0): positiveLog = ln(seed)
  elif seed < F(0): negativeLog = ln(-seed)
  let positivePrefix = logarithmicScanStep(positive, F(positiveLog - normalizer))
  let negativePrefix = logarithmicScanStep(negative, F(negativeLog - normalizer))
  gradientExponential(F(positivePrefix + input)) -
    gradientExponential(F(negativePrefix + input))

proc complexGradientStep[F: SomeFloat](accumulated: var Complex[float64];
    input, normalizer, seed: Complex[F]): Complex[F] {.inline.} =
  ## Tensor addition/subtraction multiply the second operand by complex alpha=1.
  type C = Complex[F]
  let alpha = C(re: F(1), im: F(0))
  let logarithm = complex.ln(conjugate(seed))
  let prefix = logarithmicScanStep(accumulated, logarithm - alpha * normalizer)
  conjugate(exponentialComplex(prefix + alpha * input))

proc cpuLogcumsumexpGradient*[T: SomeFloat or Complex](input, normalizer,
    seed: Tensor[T]; dimension: int): Tensor[T] =
  ## Normalizer is the saved dense forward output; seed/input may be arbitrary views.
  result = newTensorUninit[T](input.shape)
  if result.size == 0: return
  let destination = result.storage.raw_buffer
  let source = input.storage.raw_buffer
  let rounded = normalizer.storage.raw_buffer
  let weights = seed.storage.raw_buffer
  if input.rank == 0:
    destination[0] = weights[seed.offset]
    return
  let length = uint(input.shape[dimension])
  var outer = 1'u
  var inner = 1'u
  for index in 0 ..< dimension: outer *= uint(input.shape[index])
  for index in dimension + 1 ..< input.rank: inner *= uint(input.shape[index])
  let groups = outer * inner
  let inputStride = input.strides[dimension]
  let seedStride = seed.strides[dimension]
  if groups == 1:
    when T is Complex:
      var accumulated = Complex[float64](re: -Inf, im: 0.0)
    else:
      var positive = -Inf
      var negative = -Inf
    var index = length
    while index > 0:
      dec index
      let position = int(index)
      let value = source[input.offset + position * inputStride]
      let normal = rounded[normalizer.offset + position]
      let weight = weights[seed.offset + position * seedStride]
      when T is Complex:
        destination[index] = complexGradientStep(accumulated, value, normal, weight)
      else:
        destination[index] = realGradientStep(positive, negative, value, normal, weight)
    return

  # Keep independent reverse chains together to hide transcendental latency.
  const Lanes = 32'u
  let packed = input.is_C_contiguous and seed.is_C_contiguous
  var coordinates: Metadata
  coordinates.len = input.rank
  var inputBase = input.offset
  var seedBase = seed.offset
  var groupStart = 0'u
  while groupStart < groups:
    let width = min(Lanes, groups - groupStart)
    var outputBases {.noinit.}: array[Lanes, uint]
    var inputBases, seedBases {.noinit.}: array[Lanes, int]
    when T is Complex:
      var accumulated {.noinit.}: array[Lanes, Complex[float64]]
    else:
      var positive, negative {.noinit.}: array[Lanes, float64]
    for lane in 0'u ..< width:
      let group = groupStart + lane
      let base = (group div inner) * length * inner + group mod inner
      outputBases[lane] = base
      if packed:
        inputBases[lane] = input.offset + int(base)
        seedBases[lane] = seed.offset + int(base)
      else:
        inputBases[lane] = inputBase
        seedBases[lane] = seedBase
        if group + 1 < groups:
          for index in countdown(input.rank - 1, 0):
            if index == dimension: continue
            inc coordinates[index]
            inputBase += input.strides[index]
            seedBase += seed.strides[index]
            if coordinates[index] < input.shape[index]: break
            coordinates[index] = 0
            inputBase -= input.shape[index] * input.strides[index]
            seedBase -= input.shape[index] * seed.strides[index]
      when T is Complex:
        accumulated[lane] = Complex[float64](re: -Inf, im: 0.0)
      else:
        positive[lane] = -Inf
        negative[lane] = -Inf
    var index = length
    while index > 0:
      dec index
      for lane in 0'u ..< width:
        let position = outputBases[lane] + index * inner
        let value = source[inputBases[lane] + int(index) * inputStride]
        let normal = rounded[normalizer.offset + int(position)]
        let weight = weights[seedBases[lane] + int(index) * seedStride]
        when T is Complex:
          destination[position] = complexGradientStep(accumulated[lane], value, normal, weight)
        else:
          destination[position] = realGradientStep(
            positive[lane], negative[lane], value, normal, weight)
    groupStart += width
